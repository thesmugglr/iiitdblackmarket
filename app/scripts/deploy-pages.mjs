// Builds the site and publishes ONLY the static output to a GitHub Pages repository (source code stays private).
//
//   npm run deploy:pages -- <owner/repo>        e.g. npm run deploy:pages -- AbhikRao/iiitd-black-market
//
// Needs: `gh auth login` (git push over https), and production settings in app/.env.production.local:
//   VITE_SUPABASE_URL=https://<project-ref>.supabase.co
//   VITE_SUPABASE_PUBLISHABLE_KEY=<publishable or anon key>      (never a secret / service-role key)
// The target repo is public, its default branch is `main`, and Pages serves `main` from the root.
import { execFileSync } from 'node:child_process'
import { cp, mkdir, mkdtemp, readdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { loadEnv } from 'vite'
import { readClientConfig } from '../src/lib/config.ts'

const repo = process.argv[2] ?? process.env.DEPLOY_REPO
if (!repo || !/^[\w.-]+\/[\w.-]+$/.test(repo)) {
  console.error('Usage: npm run deploy:pages -- <owner/repo>')
  process.exit(1)
}
const [owner, name] = repo.split('/')
const base = `/${name}/`
const env = loadEnv('production', process.cwd(), 'VITE_')
const config = readClientConfig(env, false)
if (!config.configured) {
  console.error('Configuration is not ready (no credential values printed):')
  for (const issue of config.issues) console.error(`- ${issue}`)
  process.exit(1)
}

const keepAlive = (url, key) => `name: Keep backend active
on:
  schedule:
    - cron: '17 6 * * 1,4'
  workflow_dispatch:
permissions: {}
jobs:
  ping:
    runs-on: ubuntu-latest
    steps:
      - name: Call the public ping function
        run: |
          curl --fail --silent --show-error --max-time 30 -X POST \\
            -H "apikey: ${key}" -H "Content-Type: application/json" -d '{}' \\
            "${url}/rest/v1/rpc/ping"
`

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: 'inherit', ...opts })
const out = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', ...opts }).trim()

// Demo and local-login switches must never reach a public build.
const buildEnv = { ...process.env, VITE_BASE: base, VITE_SUPABASE_URL: config.url, VITE_SUPABASE_PUBLISHABLE_KEY: config.key }
delete buildEnv.VITE_DEMO
delete buildEnv.VITE_DEV_LOGIN
run('npm', ['run', 'build'], { env: buildEnv })

let source = 'unknown'
try { source = out('git', ['rev-parse', '--short', 'HEAD']) } catch { /* not a git checkout */ }

const work = await mkdtemp(join(tmpdir(), 'pages-'))
try {
  run('git', ['clone', '--depth', '1', `https://github.com/${repo}.git`, work])
  for (const entry of await readdir(work)) if (entry !== '.git') await rm(join(work, entry), { recursive: true, force: true })
  await cp('dist', work, { recursive: true })
  await mkdir(join(work, '.github/workflows'), { recursive: true })
  await writeFile(join(work, '.github/workflows/keepalive.yml'), keepAlive(config.url, config.key))
  await writeFile(join(work, 'README.md'), `# IIITD Black Market (built site)\n\nThis repository only holds the compiled static site served by GitHub Pages. It is generated by \`npm run deploy:pages\` from the private source repository; do not edit it by hand.\n\nThe workflow in \`.github/workflows/keepalive.yml\` pings the backend twice a week so a free-tier Supabase project is not paused for inactivity.\n`)
  run('git', ['add', '-A'], { cwd: work })
  const changed = out('git', ['status', '--porcelain'], { cwd: work })
  if (!changed) console.log('Nothing changed since the last deploy.')
  else {
    run('git', ['-c', 'user.name=IIITD Black Market deploy', '-c', 'user.email=deploy@users.noreply.github.com', 'commit', '-m', `Deploy build of source ${source}`], { cwd: work })
    run('git', ['push', 'origin', 'HEAD'], { cwd: work })
  }
  console.log(`\nSite: https://${owner.toLowerCase()}.github.io/${name}/`)
} finally {
  await rm(work, { recursive: true, force: true })
}
